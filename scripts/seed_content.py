def build_questions(sources):
    source_map = {s['number']: s for s in sources}
    questions = []
    for row_index, raw in enumerate(ROWS.strip().splitlines()):
        fields = raw.split('|')
        assert len(fields) == 9, (raw, len(fields))
        n, stem, good, bad1, bad2, bad3, cloze, aliases, anchor = fields
        n = int(n)
        source = source_map[n]
        paragraphs = source['answer'].split('\n\n')
        choice_anchor = CHOICE_ANCHORS.get(n, anchor)
        evidence = next((p for p in paragraphs if choice_anchor in p), None)
        if n in (1, 8, 18, 47):
            # These comparisons deliberately span both adjacent paragraphs.
            evidence = source['answer']
        assert evidence, (n, anchor)
        common = dict(source_id=source['id'], chapter=source['chapter'], reviewed=True, version=1)
        order = [bad1, bad2, bad3]
        position = row_index % 4
        order.insert(position, good)
        questions.append(dict(**common, id=f'q{n}-choice', type='single', stem=stem,
                              options=[dict(id=chr(97 + i), text=t) for i, t in enumerate(order)],
                              correct=[chr(97 + position)], answers=[],
                              explanation=f'正确项：{good}。\n\n依据原答案：{evidence}', evidence=evidence))
        # Cloze occasionally tests a second paragraph. Select its exact supporting
        # paragraph explicitly instead of using a fuzzy or keyword grading rule.
        cloze_anchor = CLOZE_ANCHORS.get(n, anchor)
        cloze_evidence = next((p for p in paragraphs if cloze_anchor in p), None)
        assert cloze_evidence, (n, cloze_anchor)
        questions.append(dict(**common, id=f'q{n}-cloze', type='cloze', stem=cloze,
                              options=[], correct=[], answers=[aliases.split('~')],
                              explanation=f'标准答案：{aliases.split("~")[0]}。\n\n依据原答案：{cloze_evidence}',
                              evidence=cloze_evidence))
        if n == 81:
            questions[-1]['numeric'] = dict(value=48, tolerance=0, unit='个百分点')
    return questions


