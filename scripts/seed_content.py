def parse_sources():
    text = INPUT.read_text(encoding='utf-8')
    chapter = None
    chapter_title = None
    sources = []
    headings = list(re.finditer(r'^(# [^\n]+|## Q(\d+)\. ([^\n]+))\n', text, re.M))
    for index, match in enumerate(headings):
        if match.group(1).startswith('# 第'):
            chapter = str(int(chapter or 0) + 1)
            chapter_title = match.group(1).split('：', 1)[1]
        elif match.group(2):
            number = int(match.group(2))
            end = headings[index + 1].start() if index + 1 < len(headings) else len(text)
            answer = text[match.end():end].strip()
            citations = [{'title': title, 'url': url} for title, url in re.findall(r'\[([^\]]+)\]\((https?://[^)]+)\)', answer)]
            sources.append(dict(id=f'Q{number}', number=number, title=match.group(3), chapter=chapter,
                                chapter_title=chapter_title, answer=answer, images=[], citations=citations))
    return sources


